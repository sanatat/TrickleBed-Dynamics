"""Synthetic calibration/holdout study for physically coupled tracer transport."""
from pathlib import Path
import csv,json
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from dataclasses import replace
from v6_model import Params
from tracer_coupled_v14 import TracerConfig,run_tracer,fit_tracer,pulse

def main():
    out=Path('results/v14_coupled');out.mkdir(parents=True,exist_ok=True)
    p=Params(n=12,t_end=500,t_step=600,wet_init=.35,wet_adv=.8,cap_tau=110,u_L=.0015)
    t=np.linspace(0,500,105)
    truth=TracerConfig(k_exchange=.0025,dispersion=1.4e-5)
    rng=np.random.default_rng(20261026)
    train_true=run_tracer(p,truth,t)
    noise=.00045
    y_train=train_true['outlet_conc']+rng.normal(0,noise,len(t))
    opt=fit_tracer(p,t,y_train)
    fitted=TracerConfig(k_exchange=opt.x[0],dispersion=opt.x[1])
    fit=run_tracer(p,fitted,t)
    # Independent synthetic data at new flow rate AND different wetting history.
    q=replace(p,u_L=p.u_L*1.35,wet_init=.65)
    hold_true=run_tracer(q,truth,t)
    y_hold=hold_true['outlet_conc']+rng.normal(0,noise,len(t))
    hold=run_tracer(q,fitted,t)
    # Without transient pore storage/exchange: compare against k approximately zero.
    baseline=run_tracer(q,TracerConfig(k_exchange=1e-9,dispersion=fitted.dispersion),t)
    rmse=lambda y,yhat:float(np.sqrt(np.mean((y-yhat)**2)))
    # Local Jacobian singular values: warning for weak parameter identifiability.
    sigma=np.linalg.svd(opt.jac,compute_uv=False)
    result=dict(kind='SYNTHETIC one-way coupled passive-tracer experiment',
        fit={'k_exchange_per_s':float(opt.x[0]),'dispersion_m2_s':float(opt.x[1])},
        truth={'k_exchange_per_s':truth.k_exchange,'dispersion_m2_s':truth.dispersion},
        train_rmse=rmse(y_train,fit['outlet_conc']),holdout_rmse=rmse(y_hold,hold['outlet_conc']),
        no_pore_exchange_baseline_holdout_rmse=rmse(y_hold,baseline['outlet_conc']),
        jacobian_singular_values=sigma.tolist(),optimization_success=bool(opt.success),
        caveats=['All RTD data synthetic, generated by the same governing equations.','Tracer one-way coupled to prescribed v6 wetting; chemistry does not affect tracer.','No 2012 CFD validation or industrial data.','Local Jacobian singular values are not robust confidence intervals.'])
    (out/'metrics.json').write_text(json.dumps(result,indent=2))
    with (out/'curves.csv').open('w',newline='') as f:
        w=csv.writer(f);w.writerow(['time_s','train_synthetic','train_fit','holdout_synthetic','holdout_pred','holdout_no_exchange'])
        w.writerows(zip(t,y_train,fit['outlet_conc'],y_hold,hold['outlet_conc'],baseline['outlet_conc']))
    fig,ax=plt.subplots(figsize=(9,5));ax.scatter(t,y_train,s=11,label='Synthetic calibration',alpha=.5);ax.plot(t,fit['outlet_conc'],label='Fitted pore-exchange tracer model');ax.set(xlabel='Time (s)',ylabel='Outlet tracer concentration (normalized inlet pulse units)',title='Coupled axial tracer calibration (synthetic)');ax.legend();fig.tight_layout();fig.savefig(out/'calibration.png',dpi=160);plt.close(fig)
    fig,ax=plt.subplots(figsize=(9,5));ax.scatter(t,y_hold,s=11,label='Independent synthetic holdout',alpha=.5);ax.plot(t,hold['outlet_conc'],label='No-refit prediction');ax.plot(t,baseline['outlet_conc'],'--',label='No pore-exchange comparison');ax.set(xlabel='Time (s)',ylabel='Outlet tracer concentration (normalized inlet pulse units)',title='Holdout: new flow and initial wetting');ax.legend();fig.tight_layout();fig.savefig(out/'holdout.png',dpi=160);plt.close(fig)
    report=f"""# v1.4 one-way coupled tracer module

This version adds a **conservative passive dissolved tracer** to the SAME 1-D axial discretization and phenomenological wetting equation underlying `v6_model.py`. Unlike the separate v1.3 gamma-RTD model, pore-liquid storage now dynamically exchanges with the mobile liquid.

It is a **one-way coupling**, not a simultaneous integration of tracer, reaction, thermal, gas and pressure fields; prescribed wetting has no feedback from tracer. No published experimental RTD observations are available.

Parameters: calibration at u={p.u_L} m/s and initial wetting {p.wet_init}; unseen synthetic holdout at u={q.u_L} m/s, initial wetting {q.wet_init}. A Gaussian pulse enters the liquid inlet. The calibration and holdout are both generated by exactly this model family with distinct random noise. This is a numerical workflow demonstration, NOT external validation.

Fitted k_exchange={fitted.k_exchange:.8g} s^-1, D_ax={fitted.dispersion:.8g} m2/s. Training RMSE={result['train_rmse']:.6g}, holdout RMSE={result['holdout_rmse']:.6g}; comparison with zero pore exchange RMSE={result['no_pore_exchange_baseline_holdout_rmse']:.6g}.

Finite-volume tracer balance uses molar inventories per bed volume and fluxes across faces, plus exactly cancelling exchange/volume-displacement fluxes. See test of volume-integrated mass balance. Positive/negative injection and boundaries are defined in source. The no-exchange comparison is illustrative, not necessarily a fair calibrated baseline.

**Limitations**: empirical wetting and transport parameters are synthetic, axial dispersion is an illustrative closure, no reaction or heat feedback, no vapor/liquid phase change, no CFD reproduction, and no experimentally supported parameter estimates.
"""
    (out/'REPORT.md').write_text(report)
    print(json.dumps(result,indent=2))
if __name__=='__main__': main()
